import { useEffect, useRef } from "react";
import type { AnswerStage, ConversationMessage } from "../api/types";
import type { PendingAnswer } from "../hooks/useConversation";
import { AnswerText } from "./AnswerText";
import { AlertIcon, SourcesIcon } from "./icons";

export type Selection = { messageId: string; number: number | null };
export const PENDING_ID = "pending";

interface Props {
  messages: ConversationMessage[];
  pending: PendingAnswer | null;
  selection: Selection | null;
  onSelect: (selection: Selection) => void;
  onRetry: (question: string) => void;
  onDismiss: () => void;
}

const STAGE_LABELS: Record<AnswerStage, string> = {
  rewriting: "Understanding the follow-up…",
  retrieving: "Searching the approved sources…",
  generating: "Writing the answer…",
};

export function ChatView({ messages, pending, selection, onSelect, onRetry, onDismiss }: Props) {
  const end = useRef<HTMLDivElement>(null);
  const pendingText = pending?.text.length ?? 0;

  useEffect(() => {
    end.current?.scrollIntoView({ block: "end" });
  }, [messages.length, pending?.stage, pendingText]);

  return (
    <div className="chat" role="log" aria-live="polite" aria-busy={pending !== null && pending.error === null}>
      {messages.map((message, i) =>
        message.role === "user" ? (
          <Question key={message.id} text={message.content} />
        ) : (
          <AnswerCard
            key={message.id}
            message={message}
            question={messages[i - 1]?.content}
            selection={selection}
            onSelect={onSelect}
            onRetry={onRetry}
          />
        ),
      )}
      {pending && (
        <>
          <Question text={pending.question} />
          <article className="answer">
            {pending.error ? (
              <div className="callout callout-danger" role="alert">
                <AlertIcon />
                <div>
                  <strong>The question could not be sent.</strong> {pending.error}
                  <div className="callout-actions">
                    <button className="button button-small" onClick={() => onRetry(pending.question)}>
                      Try again
                    </button>
                    <button className="button button-small button-ghost" onClick={onDismiss}>
                      Dismiss
                    </button>
                  </div>
                </div>
              </div>
            ) : (
              <>
                {pending.restarted && (
                  <p className="muted small">The answer is being regenerated by a fallback model.</p>
                )}
                {pending.text ? (
                  <AnswerText
                    text={pending.text}
                    streaming
                    selected={selection?.messageId === PENDING_ID ? selection.number : null}
                    onCite={(number) => onSelect({ messageId: PENDING_ID, number })}
                  />
                ) : (
                  <div className="stage">
                    <span className="pulse" aria-hidden="true" />
                    {pending.stage ? STAGE_LABELS[pending.stage] : "Sending…"}
                  </div>
                )}
              </>
            )}
          </article>
        </>
      )}
      <div ref={end} />
    </div>
  );
}

function Question({ text }: { text: string }) {
  return (
    <div className="question">
      <div className="question-bubble">{text}</div>
    </div>
  );
}

interface AnswerCardProps {
  message: ConversationMessage;
  question: string | undefined;
  selection: Selection | null;
  onSelect: (selection: Selection) => void;
  onRetry: (question: string) => void;
}

function AnswerCard({ message, question, selection, onSelect, onRetry }: AnswerCardProps) {
  const selectedHere = selection?.messageId === message.id;
  const rewritten = message.standalone_question && question && message.standalone_question !== question;

  if (message.status === "failed") {
    return (
      <article className="answer">
        <div className="callout callout-danger" role="alert">
          <AlertIcon />
          <div>
            {message.content}
            {question && (
              <div className="callout-actions">
                <button className="button button-small" onClick={() => onRetry(question)}>
                  Ask again
                </button>
              </div>
            )}
          </div>
        </div>
      </article>
    );
  }

  return (
    <article className={`answer ${selectedHere ? "is-selected" : ""}`}>
      {message.status === "insufficient_evidence" && (
        <div className="callout callout-warning">
          <AlertIcon />
          <div>
            <strong>Not fully covered by the approved sources.</strong> Treat this answer as incomplete.
          </div>
        </div>
      )}
      <AnswerText
        text={message.content}
        selected={selectedHere ? (selection?.number ?? null) : null}
        onCite={(number) => onSelect({ messageId: message.id, number })}
      />
      <footer className="answer-footer">
        {message.citations.length > 0 && (
          <button className="link-button" onClick={() => onSelect({ messageId: message.id, number: null })}>
            <SourcesIcon width={15} height={15} />
            {message.citations.length} {message.citations.length === 1 ? "source" : "sources"}
          </button>
        )}
        {rewritten && (
          <span className="muted small" title="Follow-up questions are rewritten to stand alone for searching">
            Searched as: “{message.standalone_question}”
          </span>
        )}
      </footer>
    </article>
  );
}
